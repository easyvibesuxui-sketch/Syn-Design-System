// Builds src/styles/tokens.css and src/tokens.ts from tokens/syn.tokens.json.
// Primitives become --syn-* custom properties; semantic tokens alias them with var().
// The Figma library has one (light) theme, so there is no theme override block.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(readFileSync(resolve(root, 'tokens/syn.tokens.json'), 'utf8'));

// Token path -> CSS variable name. Semantic colours drop their "semantic.color" prefix
// so components read --syn-text-primary rather than --syn-semantic-color-text-primary.
function varName(path) {
  const p = [...path];
  if (p[0] === 'primitive') p.shift();
  if (p[0] === 'semantic') {
    p.shift();
    if (p[0] === 'color') p.shift();
    if (p[0] === 'typography') p[0] = 'type';
  }
  return `--syn-${p.join('-')}`;
}

function walk(node, path, out) {
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    if (value && typeof value === 'object' && '$value' in value) out.push({ path: [...path, key], value: value.$value });
    else if (value && typeof value === 'object') walk(value, [...path, key], out);
  }
  return out;
}

const all = walk(src, [], []);
const byPath = new Map(all.map((t) => [t.path.join('.'), t]));

const isAlias = (v) => typeof v === 'string' && /^\{[^}]+\}$/.test(v);
const aliasPath = (v) => v.slice(1, -1);

function cssValue(v) {
  if (isAlias(v)) return `var(${varName(aliasPath(v).split('.'))})`;
  if (Array.isArray(v)) return v.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(', ');
  if (typeof v === 'object') {
    // Typography composite -> `font` shorthand.
    return `${v.fontWeight} ${v.fontSize}/${v.lineHeight} ${cssValue(v.fontFamily)}`;
  }
  return String(v);
}

function resolveValue(v) {
  if (isAlias(v)) return resolveValue(byPath.get(aliasPath(v)).value);
  if (Array.isArray(v)) return v.join(', ');
  if (typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, resolveValue(x)]));
  return v;
}

const decl = (t) => `  ${varName(t.path)}: ${cssValue(t.value)};`;
const group = (name) => all.filter((t) => t.path[0] === name);

const typography = group('semantic').filter((t) => t.path[1] === 'typography');
const utilities = typography
  .map((t) => `.syn-text-${t.path.at(-1)} { font: var(${varName(t.path)}); }`)
  .join('\n');

const css = `/* Generated by scripts/build-tokens.mjs from tokens/syn.tokens.json. Do not edit. */
:root {
${group('primitive').map(decl).join('\n')}

${group('semantic').map(decl).join('\n')}
}

${utilities}
`;

const tree = {};
for (const t of all) {
  let node = tree;
  const p = t.path;
  p.slice(0, -1).forEach((k) => (node = node[k] ??= {}));
  node[p.at(-1)] = resolveValue(t.value);
}
const ts = `// Generated by scripts/build-tokens.mjs from tokens/syn.tokens.json. Do not edit.
// Resolved values, for JS consumers (charts, canvas, tests).
export const tokens = ${JSON.stringify(tree, null, 2)} as const;

export type SynTokens = typeof tokens;
`;

mkdirSync(resolve(root, 'src/styles'), { recursive: true });
writeFileSync(resolve(root, 'src/styles/tokens.css'), css);
writeFileSync(resolve(root, 'src/tokens.ts'), ts);
console.log(`tokens: ${all.length} tokens -> src/styles/tokens.css, src/tokens.ts`);
