// Builds src/icons/icon-data.ts from icons/syn-icons.json.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { icons } = JSON.parse(readFileSync(resolve(root, 'icons/syn-icons.json'), 'utf8'));
const names = Object.keys(icons).sort();

const ts = `// Generated by scripts/build-icons.mjs from icons/syn-icons.json. Do not edit.
export const iconNames = ${JSON.stringify(names)} as const;

export type IconName = (typeof iconNames)[number];

export const iconData: Record<IconName, { width: number; height: number; body: string }> = ${JSON.stringify(
  Object.fromEntries(names.map((n) => [n, icons[n]])),
  null,
  1,
)};
`;

mkdirSync(resolve(root, 'src/icons'), { recursive: true });
writeFileSync(resolve(root, 'src/icons/icon-data.ts'), ts);
console.log(`icons: ${names.length} icons -> src/icons/icon-data.ts`);
