// Builds src/icons/icon-data.ts from icons/syn-icons.json (all 164 Figma "Main icons").
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { icons } = JSON.parse(readFileSync(resolve(root, 'icons/syn-icons.json'), 'utf8'));
const names = Object.keys(icons);

// Names used before the full Figma export, kept so existing code keeps working.
const aliases = {
  'arrow-right': 'arrow',
  'chevron-down': 'down',
  'chevron-up': 'up',
  'chevron-left': 'back',
  'chevron-right': 'next',
  'check-circle': 'check-in-circle',
  clock: 'time',
  'close-circle': 'x-in-circle',
  'eye-off': 'eye-closed',
  menu: 'burger',
  'minus-circle': 'minus-in-circle',
  'plus-circle': 'plus-in-circle',
  'more-horizontal': 'dotshorizontal',
  'more-vertical': 'dotvertical',
  refresh: 'refresh-change',
  trash: 'trash-bin',
};
for (const target of Object.values(aliases)) if (!icons[target]) throw new Error(`alias target missing: ${target}`);

const data = Object.fromEntries(
  names.map((n) => [n, { width: icons[n].width, height: icons[n].height, multicolor: icons[n].multicolor, body: icons[n].body }]),
);

const ts = `// Generated by scripts/build-icons.mjs from icons/syn-icons.json. Do not edit.
export const iconNames = ${JSON.stringify(names)} as const;

export const iconAliases = ${JSON.stringify(aliases, null, 1)} as const;

export type IconName = (typeof iconNames)[number] | keyof typeof iconAliases;

export interface IconGlyph {
  /** Native Figma artboard size. Most icons are 20 x 20. */
  width: number;
  height: number;
  /** Multicolour icons keep their Figma colours; the rest draw in currentColor. */
  multicolor: boolean;
  body: string;
}

export const iconData: Record<(typeof iconNames)[number], IconGlyph> = ${JSON.stringify(data, null, 1)};

export function getIcon(name: IconName): IconGlyph {
  return iconData[(iconAliases as Record<string, (typeof iconNames)[number]>)[name] ?? (name as (typeof iconNames)[number])];
}
`;

mkdirSync(resolve(root, 'src/icons'), { recursive: true });
writeFileSync(resolve(root, 'src/icons/icon-data.ts'), ts);
console.log(`icons: ${names.length} icons, ${Object.keys(aliases).length} aliases -> src/icons/icon-data.ts`);
