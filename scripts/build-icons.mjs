// Builds src/icons/icon-data.ts from icons/syn-icons.json (all 164 Figma "Main icons").
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { STANDARD, ILLUSTRATIONS, fit20, standardizeFolder } from './icons-to-20.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { icons } = JSON.parse(readFileSync(resolve(root, 'icons/syn-icons.json'), 'utf8'));
const names = Object.keys(icons);

// Names used before the full Figma export, kept so existing code keeps working.
const aliases = {
  'arrow-right': 'arrow',
  'chevron-down': 'down',
  'chevron-up': 'up',
  'chevron-left': 'back',
  'chevron-right': 'next',
  'check-circle': 'check-in-circle',
  clock: 'time',
  'close-circle': 'x-in-circle',
  'eye-off': 'eye-closed',
  menu: 'burger',
  'minus-circle': 'minus-in-circle',
  'plus-circle': 'plus-in-circle',
  'more-horizontal': 'dotshorizontal',
  'more-vertical': 'dotvertical',
  refresh: 'refresh-change',
  trash: 'trash-bin',
  // Figma's "File formats=Orange" is the same drawing as "Gray", so it is kept as a name only.
  'file-formats-orange': 'file-formats-gray',
};
for (const target of Object.values(aliases)) if (!icons[target]) throw new Error(`alias target missing: ${target}`);

// Every icon sits on the standard 20 x 20 board. Figma draws a few on other boards (file formats 24 x 30,
// tag2 and info-button 24 x 24, slidebar 81 x 17, check-in-circle 18 x 20, ...): those are scaled to fit 20 x 20
// and centred. The two illustrations keep their own size; they are pictures, not icons.
function standard(n) {
  const { width, height, multicolor, body } = icons[n];
  if (ILLUSTRATIONS.includes(n) || (width === STANDARD && height === STANDARD)) return { width, height, multicolor, body };
  const t = fit20(width, height);
  const transform = t.scale === 1 ? `translate(${t.x} ${t.y})` : `translate(${t.x} ${t.y}) scale(${t.scale})`;
  return { width: STANDARD, height: STANDARD, multicolor, body: `<g transform="${transform}">${body}</g>` };
}
const data = Object.fromEntries(names.map((n) => [n, standard(n)]));
const odd = names.filter((n) => !ILLUSTRATIONS.includes(n) && (data[n].width !== STANDARD || data[n].height !== STANDARD));
if (odd.length) throw new Error(`icons not on the 20 x 20 board: ${odd.join(', ')}`);

const ts = `// Generated by scripts/build-icons.mjs from icons/syn-icons.json. Do not edit.
export const iconNames = ${JSON.stringify(names)} as const;

export const iconAliases = ${JSON.stringify(aliases, null, 1)} as const;

export type IconName = (typeof iconNames)[number] | keyof typeof iconAliases;

export interface IconGlyph {
  /** Board size: 20 x 20 for every icon (the illustrations empty-list and search-empty keep their own). */
  width: number;
  height: number;
  /** Multicolour icons keep their Figma colours; the rest draw in currentColor. */
  multicolor: boolean;
  body: string;
}

export const iconData: Record<(typeof iconNames)[number], IconGlyph> = ${JSON.stringify(data, null, 1)};

export function getIcon(name: IconName): IconGlyph {
  return iconData[(iconAliases as Record<string, (typeof iconNames)[number]>)[name] ?? (name as (typeof iconNames)[number])];
}
`;

mkdirSync(resolve(root, 'src/icons'), { recursive: true });
writeFileSync(resolve(root, 'src/icons/icon-data.ts'), ts);
console.log(`icons: ${names.length} icons, ${Object.keys(aliases).length} aliases -> src/icons/icon-data.ts`);

// The exported SVG files follow the same rule.
const moved = standardizeFolder(resolve(root, 'icons/svg'));
if (moved.length) console.log(`icons/svg: ${moved.length} put on 20 x 20`);
